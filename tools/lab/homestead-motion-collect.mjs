import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=process.argv[2],out='docs/proposals/homestead-style-2026-10-14/v3/evidence';
if(!root)throw Error('Output root required');
const dirs=['v2','v3'].map(v=>path.join(root,'motion-'+v));
const reports=dirs.map(d=>JSON.parse(fs.readFileSync(d+'/report.json','utf8')));
const rows=reports.map(r=>r.measurements[0]);
assert.equal(rows[0].motionFrames.length,12);assert.deepEqual(rows[0].motionFrames,rows[1].motionFrames,'Camera, clock or RNG differs during motion');
assert.equal(rows[0].motionEndStateSha256,rows[1].motionEndStateSha256,'State differs after motion');
const compared=execFileSync(process.execPath,['tools/lab/homestead-compare.mjs',...dirs.map(d=>d+'/report.json')],{encoding:'utf8'});
fs.writeFileSync(out+'/motion-comparison.json',compared);
for(let i=0;i<dirs.length;i++)fs.copyFileSync(dirs[i]+'/report.json',out+`/motion-${i?'v3':'v2'}-report.json`);
const hashes=dirs.map(d=>fs.readdirSync(d+'/frames').filter(n=>n.endsWith('.png')).sort().map(n=>({file:n,sha256:createHash('sha256').update(fs.readFileSync(d+'/frames/'+n)).digest('hex')})));
assert(hashes.every(h=>h.length===12));
fs.writeFileSync(out+'/motion-frame-hashes.json',JSON.stringify({note:'Offline 12 frames / 8 fps; camera, clock, RNG and end state match. Raw PNG SHA256 before video encoding.',variants:hashes},null,2)+'\n');
execFileSync('ffmpeg',['-y','-framerate','8','-i',dirs[0]+'/frames/%03d.png','-framerate','8','-i',dirs[1]+'/frames/%03d.png','-filter_complex','[0:v][1:v]hstack=inputs=2','-c:v','libx264','-crf','18','-pix_fmt','yuv420p',out+'/motion-comparison.mp4'],{stdio:'ignore'});
const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-select_streams','v:0','-show_entries','stream=width,height,nb_frames,r_frame_rate,duration','-of','json',out+'/motion-comparison.mp4'],{encoding:'utf8'}));
assert.equal(probe.streams[0].nb_frames,'12');assert.equal(probe.streams[0].r_frame_rate,'8/1');assert.equal(probe.streams[0].width,1280);assert.equal(probe.streams[0].height,360);
fs.writeFileSync(out+'/motion-video-info.json',JSON.stringify(probe,null,2)+'\n');
console.log('PASS: paired motion camera/time/RNG/end save, 12 raw frames each; encoded 1280x360 / 8 fps comparison.');
